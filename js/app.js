    startSnowfall() {
        if (this._snowStarted) return;
        this._snowStarted = true;
        const canvas = document.getElementById('snow-canvas');
        if (!canvas) return;
        const ctx = canvas.getContext('2d');
        const resize = () => { canvas.width = window.innerWidth; canvas.height = window.innerHeight; };
        resize();
        window.addEventListener('resize', resize);
        const flakes = [];
        for (let i = 0; i < 45; i++) {
            flakes.push({ x: Math.random() * canvas.width, y: Math.random() * canvas.height, r: 0.8 + Math.random() * 2.1, s: 0.4 + Math.random() * 1.1, o: 0.18 + Math.random() * 0.32, drift: Math.random() * Math.PI * 2 });
        }
        const draw = () => {
            ctx.clearRect(0, 0, canvas.width, canvas.height);
            flakes.forEach(f => {
                f.y += f.s;
                f.drift += 0.01;
                f.x += Math.sin(f.drift) * 0.4;
                if (f.y > canvas.height + 6) { f.y = -6; f.x = Math.random() * canvas.width; }
                ctx.beginPath();
                ctx.arc(f.x, f.y, f.r, 0, Math.PI * 2);
                ctx.fillStyle = `rgba(255, 255, 255, ${f.o})`;
                ctx.fill();
            });
            this._snowRAF = requestAnimationFrame(draw);
        };
        draw();
    }
