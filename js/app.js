        if (now - this._taskCompletionCooldown < 1000) {
            this.showNotification('Wait', this.t('task_cooldown', { s: 1 }), 'warning');
            return;
        }
        this.isTaskRunning = true;
        this._taskCompletionCooldown = now;
        try {
            const result = await this.fetchFromServer('/api/complete-task', { taskId: taskId, taskType: taskType });
            if (result.success) {
                this.loadUserData(result.user);
                this.userCompletedTasks.add(taskId);
                if (taskType === 'community') {
                    this.communityTasks = this.communityTasks.filter(t => t.id !== taskId);
                    this.loadCommunityTasksList(true);
                } else if (taskType === 'partner') {
                    this.partnerTasks = this.partnerTasks.filter(t => t.id !== taskId);
                    this.loadPartnerTasksList(true);
                } else if (taskType === 'verify') {
                    this.verifyDbTasks = this.verifyDbTasks.filter(t => t.id !== taskId);
                    this.loadVerifyDbTasksList();
                }
                let msg = this.t('task_completed');
                if (result.reward > 0 || result.kopraReward > 0) {
                    const parts = [];
                    if (result.reward > 0) parts.push(`+${this.formatGram(result.reward)} GRAM`);
                    if (result.kopraReward > 0) parts.push(`+${this.formatKopra(result.kopraReward)} KOPRA`);
                    msg = parts.join('  ');
                }
                this.showNotification('Success', msg, 'success');
                this.vibrate('success');
                this.updateVerifyButtonState();
            } else {
                this.showNotification('Error', result.error || 'Failed', 'error');
            }
        } catch (e) {
            this.showNotification('Error', e.message || 'Failed', 'error');
        } finally {
            this.isTaskRunning = false;
        }
