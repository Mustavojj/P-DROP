    showPaymentModal(memo, amount) {
        const modal = document.getElementById('payment-modal');
        if (!modal) return;
        modal.style.display = 'flex';
        this._currentMemo = memo;
        this._currentAmount = amount;
        const walletDisplay = document.getElementById('payment-wallet-display');
        if (walletDisplay) {
            const span = walletDisplay.querySelector('span');
            if (span) span.textContent = this.config.PAYMENT_WALLET || this.config.TON_WALLET_ADDRESS || '';
        }
        const memoDisplay = document.getElementById('payment-memo-display');
        if (memoDisplay) {
            const span = memoDisplay.querySelector('span');
            if (span) span.textContent = memo;
        }
        const amountDisplay = document.getElementById('payment-amount-display');
        if (amountDisplay) {
            const span = amountDisplay.querySelector('span');
            if (span) span.textContent = `${amount.toFixed(4)} GRAM`;
        }
        const tonkeeperLink = document.getElementById('tonkeeper-link');
        if (tonkeeperLink) {
            const wallet = this.config.PAYMENT_WALLET || this.config.TON_WALLET_ADDRESS || '';
            tonkeeperLink.href = `https://app.tonkeeper.com/transfer/${wallet}?amount=${Math.floor(amount * 1e9)}&text=${memo}`;
        }
        const checkBtn = document.getElementById('check-payment-btn');
        if (checkBtn) {
            checkBtn.onclick = () => this.checkPayment();
        }
        const statusEl = document.getElementById('payment-status');
        if (statusEl) statusEl.textContent = '';
    }
    async checkPayment() {
        const statusEl = document.getElementById('payment-status');
        if (statusEl) statusEl.textContent = this.t('payment_checking');
        try {
            const taskData = this.paymentMode === 'verify' ? this.pendingVerifyTaskData : this.pendingTaskData;
            const result = await this.fetchFromServer('/api/check-payment', {
                memo: this._currentMemo,
                amount: this._currentAmount,
                taskData: taskData
            });
            if (result.success) {
                if (statusEl) statusEl.textContent = this.t('payment_verified');
                const modal = document.getElementById('payment-modal');
                if (modal) modal.style.display = 'none';
                if (this.paymentMode === 'verify') {
                    this.showNotification('Success', this.t('verify_task_added'), 'success');
                    this.pendingVerifyTaskData = null;
                    this.taskCache.verify = { data: [], timestamp: 0 };
                    this.loadVerifyDbTasksList();
                } else {
                    this.showNotification('Success', this.t('community_task_added'), 'success');
                    this.pendingTaskData = null;
                    this.taskCache.community = { data: [], timestamp: 0 };
                    this.loadCommunityTasksList(true);
                }
                this.vibrate('success');
            } else {
                if (statusEl) statusEl.textContent = result.error || this.t('payment_failed');
                this.showNotification('Error', result.error || this.t('payment_failed'), 'error');
            }
        } catch (e) {
            if (statusEl) statusEl.textContent = e.message || this.t('payment_failed');
            this.showNotification('Error', e.message || this.t('payment_failed'), 'error');
        }
    }
