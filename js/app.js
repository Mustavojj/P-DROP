    copyToClipboard(text) {
        if (!text || text === '-') return;
        navigator.clipboard.writeText(text).then(() => {
            this.showNotification(this.t('copied'), this.t('copied'), 'success');
            this.vibrate('success');
        }).catch(() => {});
    }

    vibrate(type) {
        try {
            if (window.Telegram?.WebApp?.HapticFeedback) {
                if (type === 'success') {
                    window.Telegram.WebApp.HapticFeedback.notificationOccurred('success');
                } else if (type === 'error') {
                    window.Telegram.WebApp.HapticFeedback.notificationOccurred('error');
                } else if (type === 'warning') {
                    window.Telegram.WebApp.HapticFeedback.notificationOccurred('warning');
                } else {
                    window.Telegram.WebApp.HapticFeedback.impactOccurred('light');
                }
            }
        } catch (e) {}
    }

    truncateName(name, maxLength = 15) {
        if (!name) return 'User';
        if (name.length <= maxLength) return name;
        return name.substring(0, maxLength) + '...';
    }

    t(key, params = {}) {
        let text = translations[this.lang]?.[key] || translations.en[key] || key;
        for (const [k, v] of Object.entries(params)) {
            text = text.replace(`{${k}}`, v);
        }
        return text;
    }

    formatGram(num) {
        return num.toFixed(5);
    }

    getCurrentTime() {
        return Date.now() + this.serverTimeOffset;
    }

    updateHeaderBalances() {
        const gramHeader = document.getElementById('header-gram');
        if (gramHeader) {
            gramHeader.innerHTML = `<img src="${this.config.GRAM_ICON}" class="gram-icon-header"><span>${this.formatGram(this.gramBalance)}</span>`;
        }
        const userStatus = document.getElementById('user-status');
        if (userStatus) {
            if (this.verified) {
                userStatus.className = 'user-status verified';
                userStatus.innerHTML = `<i class="fas fa-circle-check"></i><span>${this.t('verified')}</span>`;
            } else {
                userStatus.className = 'user-status unverified';
                userStatus.innerHTML = `<i class="fas fa-circle-xmark"></i><span>${this.t('unverified')}</span>`;
            }
        }
    }

    checkCooldown(endpoint) {
        const now = Date.now();
        const key = `${endpoint}_${this.tgUser?.id || 'user'}`;
        const lastCall = this._lastFetchTime.get(key) || 0;
        if (now - lastCall < 1000) {
            return false;
        }
        this._lastFetchTime.set(key, now);
        return true;
    }

    canCompleteTask() {
        const now = Date.now();
        const cooldownMs = 10000;
        if (this._taskCompletionCooldown && (now - this._taskCompletionCooldown) < cooldownMs) {
            const remaining = Math.ceil((cooldownMs - (now - this._taskCompletionCooldown)) / 1000);
            return { allowed: false, remaining };
        }
        return { allowed: true, remaining: 0 };
    }

    setTaskCooldown() {
        this._taskCompletionCooldown = Date.now();
    }

    canUsePromo() {
        const now = Date.now();
        const cooldownMs = 5000;
        if (this._promoCooldown && (now - this._promoCooldown) < cooldownMs) {
            const remaining = Math.ceil((cooldownMs - (now - this._promoCooldown)) / 1000);
            return { allowed: false, remaining };
        }
        return { allowed: true, remaining: 0 };
    }

    setPromoCooldown() {
        this._promoCooldown = Date.now();
    }

    async showAd(blockId) {
    try {
        const AdController = window.Adsgram.init({ blockId: blockId });
        await AdController.show();
        return true;
    } catch (e) {
        return false;
    }
    }
    
